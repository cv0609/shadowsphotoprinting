    public function checkout()
    {
        $user_address = '';
        $affiliate_sales = null;

        if (Auth::check() && !empty(Auth::user())) {
            $auth_id = Auth::user()->id;
            $cart = Cart::where('user_id', $auth_id)->with(['items.product', 'shippingCountry'])->first();
            $user_address = UserDetails::where('user_id', $auth_id)->first();

            if(Auth::user()->role === 'affiliate'){
                $affiliate_id = Auth::user()->affiliate->id;
                $affiliate_sales = \App\Models\AffiliateSale::getTotalsForAffiliate($affiliate_id);

                if(Session::has('shutter_point')){
                    $cart->update(['shutter_point'=>Session::get('shutter_point')]);
                }
            }

        } else {
            $session_id = Session::getId();
            $cart = Cart::where('session_id', $session_id)->with(['items.product', 'shippingCountry'])->first();
        }

        $orderType = (int) Session::get('order_type', 0);

        $shipping = $this->CartService->getShippingCharge();

        $shoppingCountry = $cart->shippingCountry
            ?? Country::where('code', Session::get('shop_shipping_country', 'AU'))->first()
            ?? Country::where('code', 'AU')->first();
        $addressCountries = Country::whereIn('code', ['AU', 'NZ'])
            ->with('states:id,country_id,name,code')
            ->orderBy('name')
            ->get(['id', 'name', 'code']);
        $addressCountryStates = $addressCountries->mapWithKeys(function ($country) {
            return [$country->code => $country->states->map(function ($state) {
                return ['id' => $state->id, 'name' => $state->name];
            })->values()];
        });
        $CartTotal = $this->CartService->getCartTotal();

        // Shipping required unless pickup. Direct /checkout must still resolve a shipping method.
        if (
            $orderType !== 1
            && $shipping
            && (string) $shipping->status === '1'
            && (float) ($CartTotal['shippingCharge'] ?? 0) <= 0
        ) {
            return redirect()->route('cart')
                ->with('error', 'Please wait for shipping options to finish loading before checkout.');
        }

        $page_content = ["meta_title" => config('constant.pages_meta.checkout.meta_title'), "meta_description" => config('constant.pages_meta.checkout.meta_description')];

        return view('front-end.checkout', compact('cart','affiliate_sales', 'CartTotal', 'shipping', 'addressCountries', 'addressCountryStates', 'shoppingCountry', 'page_content', 'user_address'));
    }

    public function createCustomer(Request $request)
    {
        $source = $request->input('stripeToken'); // Token generated by Stripe.js
        $email = $request->input('email');
        
        if(!Auth::check()){
        $existingUser = User::where('email', $email)->first();
            if($existingUser !== null){
                return response()->json(['error' => true, 'message' => 'This email already exists. Please log in to continue.']);
            }
        }

        $shoppingCountryCode = $this->shoppingCountryCode();
        $state_name = $this->addressStateName($request->input('state'), $shoppingCountryCode);
        $ship_state_name = $this->addressStateName($request->input('ship_state'), $shoppingCountryCode);

        $address = $this->orderAddress($request, $state_name, $ship_state_name);

        Session::put('order_address', $address);
    
        $existingCustomer = $this->stripe->searchCustomerByEmail($email);
    
        if (!$existingCustomer) {
            try {
                $stripeCustomer = $this->stripe->createCustomer($email, $source);
    
                StripeLogs::create(['logs' => json_encode($stripeCustomer)]);
    
                $customer_id = $stripeCustomer->id ?? null;

            } catch (\Exception $e) {
                return response()->json(['error' => true, 'message' => 'Stripe customer creation failed', 'data' => $e->getMessage()]);
            }
        } else {
            $customer_id = $existingCustomer->id;
    
            // Attach the new token to the existing customer
            try {
               $newSource = \Stripe\Customer::createSource(
                    $customer_id,
                    ['source' => $source]
                );

                \Stripe\Customer::update(
                    $customer_id,
                    [
                        'default_source' => $newSource->id
                    ]
                );

            } catch (\Exception $e) {
                return response()->json(['error' => true, 'message' => 'Failed to attach payment method', 'data' => $e->getMessage()]);
            }
        }
    
        return response()->json([ 'error'=> false, 'id' => $customer_id]);
    }
    
    private function orderAddress($request, $state_name, $ship_state_name)
    {
        $shoppingCountryCode = $this->shoppingCountryCode();

        $address = [
            'fname' => $request->fname,
            'lname' => $request->lname,
            'street1' => $request->street1,
            'street2' => $request->street2,
            'company_name' => $request->company_name ?? '',
            'country_region' => $this->addressCountryName($shoppingCountryCode),
            'state' => $state_name,
            'postcode' => $request->postcode,
            'phone' => $request->phone,
            'suburb' => $request->suburb,
            'email' => $request->email,
            'username' => $request->username,
            'password' => $request->password,
            'payment_method' => $request->payment_method,
            'shipping_charge' => $request->shipping_charge,
            'order_type' => $request->customer_order_type,
        ];

         if (!Auth::check()) {
            
            $data = ['fname'=>$request->fname,'lname'=>$request->lname,'username'=>$request->username,'email'=>$request->email,'password'=>$request->password];

            $this->createSiteUser($data);
        }


        // Check if shipping details are provided
        if (isset($request->isShippingAddress) && $request->isShippingAddress == true) {
            $address += [ // Use the += operator to merge arrays
                'ship_fname' => $request->ship_fname,
                'ship_lname' => $request->ship_lname,
                'ship_company' => $request->ship_company,
                'ship_street1' => $request->ship_street1,
                'ship_street2' => $request->ship_street2,
                'ship_suburb' => $request->ship_suburb,
                'ship_state' => $ship_state_name,
                'ship_postcode' => $request->ship_postcode,
                'isShippingAddress' => $request->isShippingAddress,
                'ship_country_region' => $this->addressCountryName($shoppingCountryCode),
                'order_comments' => $request->order_comments
            ];
        }

        return $address;
    }

    private function shoppingCountryCode()
    {
        $cart = Auth::check()
            ? Cart::where('user_id', Auth::id())->first()
            : Cart::where('session_id', Session::getId())->first();
        $countryCode = $cart ? $cart->shippingCountry()->value('code') : null;

        return in_array($countryCode, ['AU', 'NZ'], true)
            ? $countryCode
            : Session::get('shop_shipping_country', 'AU');
    }

    private function addressCountryName($countryCode)
    {
        return Country::whereIn('code', ['AU', 'NZ'])
            ->where('code', strtoupper((string) $countryCode))
            ->value('name')
            ?? config('constant.default_country');
    }

    private function addressStateName($state, $countryCode)
    {
        if ($state === null || $state === '') {
            return '';
        }

        if (is_numeric($state)) {
            return State::whereKey($state)
                ->whereHas('country', function ($query) use ($countryCode) {
                    $query->whereIn('code', ['AU', 'NZ'])
                        ->where('code', strtoupper((string) $countryCode));
                })
                ->value('name')
                ?? '';
        }

        return trim((string) $state);
    }

    public function chargeCustomer(Request $request)
    {
        $customerId = $request->input('customer_id');
        $amount = $request->input('amount');
        $stripeToken = $request->input('stripeToken');

        try {
            $customer = \Stripe\Customer::retrieve($customerId);
    
            if (!$customer || empty($stripeToken)) {
                return response()->json(['error' => true, 'message' => 'Customer does not have a payment method']);
            }
    
            $source = $customer->default_source;
            //$source = $stripeToken;
    
            $charge = \Stripe\Charge::create([
                'customer' => $customerId,
                'amount' => $amount,
                'currency' => 'AUD',
                'source' => $source, // Use the attached source
                'description' => 'Order Payment',
            ]);
    
            StripeLogs::create(['logs' => json_encode($charge)]);
    
            if (isset($charge->status) && in_array($charge->status, ['succeeded', 'processing', 'amount_capturable_updated'])) {
                return $this->createOrder($charge);
            } else {
                return response()->json(['error' => true, 'message' => 'Payment failed', 'data' => $charge]);
            }
        } catch (\Exception $e) {
            return response()->json(['error' => true, 'message' => 'Charge request failed', 'data' => $e->getMessage()]);
        }
    }
    
    
    private function createSiteUser($data){
        if(!Auth::check()){
            //$password = Str::random(8);
            $password = $data['password'];
            $hashedPassword = Hash::make($password);
              $user = User::create([
                'first_name' => $data['fname'],
                'last_name' => $data['lname'],
                'username' => $data['username'],
                'email' => $data['email'],
                'password' => $hashedPassword,
                'is_email_verified' => '1',
            ]);

            // Check referral session
            if (session()->has('referral_code')) {
                $referrer = Affiliate::where('referral_code', session('referral_code'))->first();
                
                if ($referrer) {
                    // Optionally log referral or save reference
                    $user->referred_by = $referrer->user_id; // Add 'referred_by' column in users table if needed
                    $user->save();

                    // Increase referrer's stats
                    $referrer->increment('referral_count');
                }
            }

            $session_id = Session::getId();
            $cart = Cart::where('session_id', $session_id)->first();
            $cart->update(['user_id'=>$user->id]);

            Auth::loginUsingId($user->id);
        }

    }

